#!/usr/bin/env python3
"""Regenerate the checked-in GPU polygon kernel; not required at build time."""
from pathlib import Path
import struct
import subprocess
import tempfile

here = Path(__file__).resolve().parent
with tempfile.TemporaryDirectory(prefix="hybris-polygon-") as temporary:
    target = Path(temporary) / "polygon.spv"
    subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.1",
                    str(here / "polygon_indices.comp"), "-o", str(target)], check=True)
    subprocess.run(["spirv-val", "--target-env", "vulkan1.1", str(target)], check=True)
    binary = target.read_bytes()
    words = struct.unpack("<" + "I" * (len(binary) // 4), binary)
    rows = "".join("    " + ", ".join(f"0x{w:08x}" for w in words[i:i+8]) + ",\n"
                   for i in range(0, len(words), 8))
    (here / "polygon_indices.inc").write_text(
        "// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by generate-polygon.py.\n"
        "static const uint32_t hybris_polygon_indices_spv[] = {\n" + rows + "};\n")
