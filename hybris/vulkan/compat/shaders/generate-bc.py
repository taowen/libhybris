"""Regenerate and validate the committed MaliBridge-derived BC kernels."""
from pathlib import Path
import os
import struct
import subprocess
import tempfile

here = Path(__file__).resolve().parent
variants = [(f'bc{family}', [f'FMT_BC{family}']) for family in ('1', '2', '3', '4', '5', '6H', '7')]
variants += [('rgb8', ['FMT_BC1', 'OUT_RGB8']), ('rgb16', ['FMT_BC6H', 'OUT_RGB16'])]
variants += [(f'tx_bc{family}', [f'FMT_BC{family}', encoder]) for family, encoder in
             [('1', 'ENC_ETC2'), ('2', 'ENC_ASTC'), ('3', 'ENC_ASTC'),
              ('4', 'ENC_EAC'), ('5', 'ENC_EAC'), ('7', 'ENC_ASTC')]]
variants += [('bc1_packed', ['FMT_BC1', 'PACK16']), ('tx_bc6h', ['FMT_BC6H', 'ENC_ASTC_HDR'])]
rows = ['/* SPDX-License-Identifier: GPL-3.0-or-later */',
        '/* Generated by generate-bc.py; see MALIBRIDGE.md and LICENSE.bcdec. */']
with tempfile.TemporaryDirectory(prefix='hybris-bc-') as temporary:
    target = Path(temporary) / 'bc.spv'
    for name, defines in variants:
        subprocess.run([os.environ.get('GLSLC', 'glslc'), '-fshader-stage=comp',
                        '--target-env=vulkan1.1', '-O', *['-D' + d for d in defines],
                        str(here / 'bc_decode.comp'), '-o', str(target)], check=True)
        subprocess.run([os.environ.get('SPIRV_VAL', 'spirv-val'), '--target-env',
                        'vulkan1.1', str(target)], check=True)
        binary = target.read_bytes()
        words = struct.unpack('<' + 'I' * (len(binary) // 4), binary)
        rows += [f'static const uint32_t hybris_bc_{name.lower()}_spv[] = {{']
        rows += ['    ' + ', '.join(f'0x{w:08x}' for w in words[i:i+8]) + ','
                 for i in range(0, len(words), 8)]
        rows += ['};']
(here / 'bc_decode.inc').write_text('\n'.join(rows) + '\n', newline='\n')
